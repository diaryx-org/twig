// Build the twig WebAssembly module and inline it into the TypeScript source.
//
// Builds `twig-capi` (twig's C ABI, with every language twig ships compiled
// in) for wasm32 with the size-first `wasm` profile, then base64-encodes the
// module into `src/wasm-bytes.ts`. Inlining (rather than shipping a separate
// `.wasm`) keeps the published package a single JS payload that loads
// identically under Node and every bundler, with no `fetch`/`fs` path to
// special-case. The module imports nothing, so it instantiates synchronously.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(here, "..", "..", "..");
const srcDir = resolve(here, "..", "src");

const args = ["build", "-p", "twig-capi", "--lib", "--profile", "wasm", "--target", "wasm32-unknown-unknown"];
console.error(`· cargo ${args.join(" ")}`);
execFileSync("cargo", args, { cwd: workspace, stdio: "inherit" });
const wasm = readFileSync(join(workspace, "target", "wasm32-unknown-unknown", "wasm", "twig.wasm"));

const imports = WebAssembly.Module.imports(new WebAssembly.Module(wasm));
if (imports.length > 0) {
  throw new Error(`twig.wasm imports ${imports.map((i) => `${i.module}.${i.name}`).join(", ")}; the binding supplies none`);
}

const base64 = wasm.toString("base64");
console.error(`· twig.wasm ${(wasm.length / 1024).toFixed(1)} KiB → ${(base64.length / 1024).toFixed(1)} KiB base64`);

const banner = `// @generated by scripts/build-wasm.mjs — do not edit by hand.
// The twig core (crates/twig-capi) compiled to a wasm32 module,
// base64-encoded. Regenerate with \`npm run build:wasm\`.
`;

// Chunk the literal so editors and diff tools don't choke on one
// multi-megabyte line, and emit it as an ARRAY joined at runtime rather than
// a `"a" + "b" + …` expression: a deep `+`-chain is parsed by recursive
// descent and overflows the stack of Node's type-stripper and some bundlers.
const chunks = [];
for (let i = 0; i < base64.length; i += 120) chunks.push(base64.slice(i, i + 120));
const literal = chunks.map((c) => `  "${c}",`).join("\n");

mkdirSync(srcDir, { recursive: true });
writeFileSync(join(srcDir, "wasm-bytes.ts"), `${banner}export const WASM_BASE64: string = [\n${literal}\n].join("");\n`);
console.error("· wrote src/wasm-bytes.ts");
